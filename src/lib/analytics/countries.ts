export const isKnownCountry = (
  code: string | null | undefined
): code is string =>
  typeof code === "string" &&
  /^[A-Z]{2}$/.test(code) &&
  code !== "XX" &&
  code !== "T1";

export const countryName = (code: string) => {
  if (!isKnownCountry(code)) {
    return "Unknown";
  }
  return COUNTRY_NAMES[code] || code;
};
